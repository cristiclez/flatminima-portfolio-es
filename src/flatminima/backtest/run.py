"""Backtest the stored rolling forecasts and write a results table and a Markdown report.

    python -m flatminima.backtest.run
    python -m flatminima.backtest.run --table risk_forecasts_w500 --report docs/backtest_w500.md

A test is reported as "passed" when it does NOT reject at the 5% level. With many tests, a
few rejections are expected by chance; the report states the counts rather than hiding them.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from flatminima.backtest.tests import (
    acerbi_szekely,
    christoffersen_cc,
    christoffersen_independence,
    kupiec_pof,
    traffic_light_windows,
)
from flatminima.data import db

ALPHA = 0.05


def _row(series, method, target, res) -> dict:
    return {
        "series": series,
        "method": method,
        "target": target,
        "test": res.name,
        "statistic": res.statistic,
        "p_value": res.p_value,
        "n_obs": res.n_obs,
        "n_exceptions": res.n_exceptions,
        "reject_5pct": bool(res.p_value < ALPHA),
    }


def backtest_series(df: pd.DataFrame, n_sims: int = 10_000, seed: int = 0) -> pd.DataFrame:
    """All tests for one series of forecasts (``df`` is one series, sorted by date)."""
    name = str(df["series"].iloc[0])
    loss = -df["ret"].to_numpy()
    window = int(df["window"].iloc[0])
    rows = []

    for method, col99 in (("FHS-GJR", "var_99"), ("Historical (unfiltered)", "hs_var_99")):
        hits = loss > df[col99].to_numpy()
        rows += [
            _row(name, method, "VaR 99%", kupiec_pof(hits, 0.99)),
            _row(name, method, "VaR 99%", christoffersen_independence(hits)),
            _row(name, method, "VaR 99%", christoffersen_cc(hits, 0.99)),
        ]
    hits975 = loss > df["var_975"].to_numpy()
    rows += [
        _row(name, "FHS-GJR", "VaR 97.5%", kupiec_pof(hits975, 0.975)),
        _row(name, "FHS-GJR", "VaR 97.5%", christoffersen_cc(hits975, 0.975)),
    ]

    tails = df[[c for c in df.columns if c.startswith("zq_")]].to_numpy()
    es = acerbi_szekely(
        df["ret"].to_numpy(),
        df["mu"].to_numpy(),
        df["sigma"].to_numpy(),
        df["var_975"].to_numpy(),
        df["es_975"].to_numpy(),
        tails,
        window=window,
        tail_prob=0.025,
        n_sims=n_sims,
        seed=seed,
    )
    for tname, stat, pv in (
        ("Acerbi-Szekely Z1", es.z1, es.p_z1),
        ("Acerbi-Szekely Z2", es.z2, es.p_z2),
    ):
        rows.append(
            {
                "series": name,
                "method": "FHS-GJR",
                "target": "ES 97.5%",
                "test": tname,
                "statistic": stat,
                "p_value": pv,
                "n_obs": es.n_obs,
                "n_exceptions": es.n_exceptions,
                "reject_5pct": bool(pv < ALPHA),
            }
        )
    return pd.DataFrame(rows)


def traffic_light_table(df: pd.DataFrame) -> pd.DataFrame:
    """Basel traffic-light shares over rolling 250-day windows (VaR 99%), both methods."""
    name = str(df["series"].iloc[0])
    loss = -df["ret"].to_numpy()
    out = []
    for method, col in (("FHS-GJR", "var_99"), ("Historical (unfiltered)", "hs_var_99")):
        tl = traffic_light_windows(loss > df[col].to_numpy(), 250, 0.99)
        out.append({"series": name, "method": method, **tl})
    return pd.DataFrame(out)


def _markdown(res: pd.DataFrame, tl: pd.DataFrame, df: pd.DataFrame, table: str) -> str:
    d0, d1 = pd.to_datetime(df["date"]).min().date(), pd.to_datetime(df["date"]).max().date()
    n_tests = len(res)
    n_rej = int(res["reject_5pct"].sum())
    lines = [
        "# Backtest results",
        "",
        f"Generated by `python -m flatminima.backtest.run --table {table}`. "
        "Data: Yahoo Finance adjusted closes (not redistributed); model: GJR-GARCH(1,1)-t with "
        f"filtered historical simulation, window {int(df['window'].iloc[0])} days.",
        f"Out-of-sample period: {d0} to {d1}. Significance level 5%. "
        "Results are not corrected for multiple testing.",
        "",
        f"**Tests run: {n_tests}; rejections at 5%: {n_rej}.**",
        "",
        "| Series | Method | Target | Test | Exceptions / N | Statistic | p-value | Reject 5% |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in res.itertuples():
        lines.append(
            f"| {r.series} | {r.method} | {r.target} | {r.test} | {r.n_exceptions} / {r.n_obs} "
            f"| {r.statistic:.3f} | {r.p_value:.4f} | {'yes' if r.reject_5pct else 'no'} |"
        )
    lines += [
        "",
        "## Basel traffic light (VaR 99%, rolling 250-day windows)",
        "",
        "| Series | Method | Windows | Green | Yellow | Red | Max exceptions in a window |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in tl.itertuples():
        lines.append(
            f"| {r.series} | {r.method} | {int(r.n_windows)} | {r.share_green:.1%} "
            f"| {r.share_yellow:.1%} | {r.share_red:.1%} | {int(r.max_exceptions)} |"
        )
    lines += ["", "Z1/Z2 p-values are one-sided Monte Carlo (H1: ES underestimated).", ""]
    return "\n".join(lines)


def run(
    db_path: str | Path,
    table: str = "risk_forecasts",
    report: str | Path | None = "docs/backtest_results.md",
    n_sims: int = 10_000,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Backtest every series in ``table``; store ``backtest_results`` and optionally a report."""
    con = db.connect(db_path)
    fc = con.execute(f'SELECT * FROM "{table}" ORDER BY series, date').df()
    results, lights = [], []
    for _, g in fc.groupby("series", sort=False):
        results.append(backtest_series(g.reset_index(drop=True), n_sims=n_sims))
        lights.append(traffic_light_table(g.reset_index(drop=True)))
    res, tl = pd.concat(results, ignore_index=True), pd.concat(lights, ignore_index=True)
    res_tab = f"backtest_results_{table}"
    con.register("_res", res)
    con.execute(f'CREATE OR REPLACE TABLE "{res_tab}" AS SELECT * FROM _res')
    con.unregister("_res")
    con.close()
    if report:
        Path(report).parent.mkdir(parents=True, exist_ok=True)
        Path(report).write_text(_markdown(res, tl, fc, table), encoding="utf-8")
    pd.set_option("display.width", 200)
    print(res.drop(columns=["n_obs"]).round(4).to_string(index=False))
    print(tl.round(3).to_string(index=False))
    print(f"\nrejections at 5%: {int(res['reject_5pct'].sum())} of {len(res)} tests")
    return res, tl


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--db", default="data/flatminima.duckdb")
    p.add_argument("--table", default="risk_forecasts")
    p.add_argument("--report", default="docs/backtest_results.md")
    p.add_argument("--n-sims", type=int, default=10_000)
    a = p.parse_args()
    run(a.db, a.table, a.report, a.n_sims)


if __name__ == "__main__":
    main()
